// Writes apps/api/src/lib/signoffFonts.ts from the TTFs in
// apps/api/assets/signoff-fonts/. The fonts are inlined as base64 for the same
// reason the sign-off images are (signoffAssets.ts): the Vercel bundle
// (scripts/bundle-api.mjs) carries no file system.
//
// The TTFs are Google Fonts' own Latin-1 subsets (css2 with `text=` set to
// U+0020–U+007E, U+00A0–U+00FF and the curly quotes / dashes / bullet /
// ellipsis / ×), fetched 2026-11-17. All are under the SIL Open Font License,
// which allows embedding them in documents. To change a font, replace the TTF
// and run:  node scripts/build-signoff-fonts.mjs   (from app/)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(app, 'apps/api/assets/signoff-fonts');
const files = readdirSync(dir).filter((f) => f.endsWith('.ttf')).sort();

const key = (f) => f.replace(/\.ttf$/, '').replace(/[^A-Za-z0-9]+/g, '_');
const lines = [
  '// GENERATED by scripts/build-signoff-fonts.mjs from apps/api/assets/signoff-fonts/*.ttf.',
  '// Do not edit: replace the TTF and re-run the script. SIL Open Font License.',
  '',
  'export const SIGNOFF_FONTS = {',
  ...files.map((f) => `  ${key(f)}: '${readFileSync(join(dir, f)).toString('base64')}',`),
  '} as const;',
  '',
  'export type SignoffFontName = keyof typeof SIGNOFF_FONTS;',
  '',
];
writeFileSync(join(app, 'apps/api/src/lib/signoffFonts.ts'), lines.join('\n'));
console.log(`signoffFonts.ts: ${files.length} fonts (${files.map(key).join(', ')})`);
